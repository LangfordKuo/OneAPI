use std::{fs::OpenOptions, io::Write};

use axum::{extract::State, Json};
use axum_extra::extract::cookie::CookieJar;
use serde::{Deserialize, Serialize};

use crate::{config::Config, error::AppError, models, security, state::AppState};

use super::auth;

#[derive(Debug, Serialize)]
pub struct SetupStatus {
    pub initialized: bool,
    pub version: &'static str,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub addr: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub data_dir: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub database: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub env_path: Option<String>,
}

pub async fn status(State(state): State<AppState>) -> Result<Json<SetupStatus>, AppError> {
    let initialized = models::admin::count(&state.db).await? > 0;

    if initialized {
        return Ok(Json(SetupStatus {
            initialized,
            version: env!("CARGO_PKG_VERSION"),
            addr: None,
            data_dir: None,
            database: None,
            env_path: None,
        }));
    }

    let database = state.config.database_url.clone().unwrap_or_else(|| {
        absolute_path(&state.config.database_path)
            .display()
            .to_string()
    });
    let data_dir = absolute_path(&state.config.data_dir);

    Ok(Json(SetupStatus {
        initialized,
        version: env!("CARGO_PKG_VERSION"),
        addr: Some(state.config.addr.to_string()),
        data_dir: Some(data_dir.display().to_string()),
        database: Some(database),
        env_path: Some(data_dir.join(".env").display().to_string()),
    }))
}

#[derive(Debug, Deserialize)]
pub struct SetupInput {
    pub username: String,
    pub password: String,
    #[serde(default)]
    pub site_name: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct SetupResult {
    pub username: String,
    pub env_written: bool,
    pub env_path: String,
    pub message: String,
}

pub async fn setup(
    State(state): State<AppState>,
    jar: CookieJar,
    Json(input): Json<SetupInput>,
) -> Result<(CookieJar, Json<SetupResult>), AppError> {
    if models::admin::count(&state.db).await? > 0 {
        return Err(AppError::BadRequest(
            "OneAPI is already initialized".to_string(),
        ));
    }

    let username = input.username.trim();
    if username.is_empty() {
        return Err(AppError::BadRequest("username is required".to_string()));
    }
    if input.password.chars().count() < 8 {
        return Err(AppError::BadRequest(
            "password must be at least 8 characters".to_string(),
        ));
    }

    let password_hash = security::hash_password(&input.password).map_err(AppError::Internal)?;
    let admin_id =
        match models::admin::create(&state.db, username, &password_hash, models::now_ms()).await {
            Ok(admin_id) => admin_id,
            Err(error) => {
                if models::admin::count(&state.db).await.unwrap_or(0) > 0 {
                    return Err(AppError::BadRequest(
                        "OneAPI is already initialized".to_string(),
                    ));
                }
                return Err(AppError::Database(error));
            }
        };

    if let Some(site_name) = input
        .site_name
        .as_deref()
        .map(str::trim)
        .filter(|value| !value.is_empty())
    {
        models::setting::upsert(&state.db, "site_name", site_name).await?;
        // /api/site is public and the setup page already fetched it, so the
        // cached name must be dropped or the new one stays hidden for 30s.
        state.cache.invalidate_site_name();
    }

    let (env_written, env_path, message) = match write_env_file(&state.config, username) {
        Ok(result) => result,
        Err(error) => (
            false,
            absolute_path(&state.config.data_dir)
                .join(".env")
                .display()
                .to_string(),
            format!("管理员已创建，但写入 .env 失败：{error}"),
        ),
    };

    let jar = auth::issue_session(&state, jar, admin_id).await?;

    Ok((
        jar,
        Json(SetupResult {
            username: username.to_string(),
            env_written,
            env_path,
            message,
        }),
    ))
}

fn write_env_file(config: &Config, username: &str) -> std::io::Result<(bool, String, String)> {
    let data_dir = absolute_path(&config.data_dir);
    let path = data_dir.join(".env");
    let path_display = path.display().to_string();

    if path.exists() {
        return Ok((false, path_display, "配置文件已存在，未覆盖。".to_string()));
    }

    let mut contents = String::new();
    contents.push_str("# Generated by OneAPI setup.\n");
    contents
        .push_str("# Loaded on startup only for keys not already present in the environment.\n");
    contents.push_str(&format!("ONEAPI_ADDR={}\n", config.addr));
    contents.push_str(&format!("ONEAPI_DATA_DIR={}\n", data_dir.display()));
    if let Some(url) = &config.database_url {
        contents.push_str(&format!("ONEAPI_DATABASE_URL={}\n", url));
    }
    contents.push_str(&format!("ONEAPI_LOG_LEVEL={}\n", config.log_level));
    contents.push_str(&format!("ONEAPI_COOKIE_SECURE={}\n", config.cookie_secure));
    contents.push_str(&format!("ONEAPI_TRUST_PROXY={}\n", config.trust_proxy));
    contents.push_str(&format!("ONEAPI_ADMIN_USER={}\n", username));
    contents.push_str("# The admin password is stored as an Argon2 hash in SQLite.\n");
    contents
        .push_str("# Set ONEAPI_ADMIN_PASSWORD only when re-bootstrapping an empty admin table.\n");
    contents.push_str("# ONEAPI_ADMIN_PASSWORD=\n");
    contents.push_str("# Optional: use a fixed secret instead of data/master.key.\n");
    contents.push_str("# ONEAPI_SECRET=\n");

    match write_new_file(&path, contents.as_bytes()) {
        Ok(()) => Ok((true, path_display, "已创建 .env 并完成初始化。".to_string())),
        Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {
            Ok((false, path_display, "配置文件已存在，未覆盖。".to_string()))
        }
        Err(error) => Err(error),
    }
}

fn absolute_path(path: &std::path::Path) -> std::path::PathBuf {
    std::path::absolute(path).unwrap_or_else(|_| path.to_path_buf())
}

#[cfg(unix)]
fn write_new_file(path: &std::path::Path, contents: &[u8]) -> std::io::Result<()> {
    use std::os::unix::fs::OpenOptionsExt;

    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(path)?;
    file.write_all(contents)
}

#[cfg(not(unix))]
fn write_new_file(path: &std::path::Path, contents: &[u8]) -> std::io::Result<()> {
    let mut file = OpenOptions::new().write(true).create_new(true).open(path)?;
    file.write_all(contents)
}
